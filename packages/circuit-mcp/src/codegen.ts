/**
 * `circuit mcp pull` — generate circuit.mcp.d.ts so ctx.mcp(...).call(...)
 * is typed against the servers' real input schemas. Covers the JSON Schema
 * subset MCP tools use in practice; anything else becomes JsonValue.
 */
import type { ToolInfo } from './gateway.js';

type Schema = Record<string, unknown>;

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));

export function schemaToTs(schema: unknown, depth = 0): string {
  if (!schema || typeof schema !== 'object' || depth > 12) return 'JsonValue';
  const s = schema as Schema;
  if (Array.isArray(s.enum)) return s.enum.map((v) => JSON.stringify(v)).join(' | ') || 'never';
  if ('const' in s) return JSON.stringify(s.const);
  for (const combo of ['anyOf', 'oneOf'] as const) {
    if (Array.isArray(s[combo])) return (s[combo] as unknown[]).map((x) => schemaToTs(x, depth + 1)).join(' | ');
  }
  const type = s.type;
  if (Array.isArray(type)) return type.map((t) => schemaToTs({ ...s, type: t }, depth + 1)).join(' | ');
  switch (type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `Array<${schemaToTs(s.items, depth + 1)}>`;
    case 'object': {
      const props = (s.properties ?? {}) as Record<string, unknown>;
      const required = new Set(Array.isArray(s.required) ? (s.required as string[]) : []);
      const pad = '  '.repeat(depth + 3);
      const lines = Object.entries(props).map(
        ([k, v]) => `${pad}${key(k)}${required.has(k) ? '' : '?'}: ${schemaToTs(v, depth + 1)};`,
      );
      if (lines.length === 0) return 'Record<string, JsonValue>';
      return `{\n${lines.join('\n')}\n${'  '.repeat(depth + 2)}}`;
    }
    default:
      return 'JsonValue';
  }
}

export function generateDeclarations(byConnection: Record<string, ToolInfo[]>): string {
  const out = [
    '// Generated by `circuit mcp pull` — do not edit; re-run it when servers change.',
    "import type { JsonValue } from '@graphmind-ai/circuit-schema';",
    '',
    "declare module '@graphmind-ai/circuit-sdk' {",
    '  interface McpRegistry {',
  ];
  for (const [connection, tools] of Object.entries(byConnection).sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`    ${key(connection)}: {`);
    for (const tool of [...tools].sort((a, b) => a.name.localeCompare(b.name))) {
      if (tool.description) out.push(`      /** ${tool.description.replaceAll('*/', '* /').split('\n')[0]} */`);
      out.push(`      ${key(tool.name)}: ${schemaToTs(tool.inputSchema, 1)};`);
    }
    out.push('    };');
  }
  out.push('  }', '}', '');
  return out.join('\n');
}
