/**
 * M1: `jack init` output and the loaders. The generated jack.yaml must parse
 * back into a config that compiles to exactly the default manifest — the
 * file is a faithful, reviewable statement of the defaults.
 */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, describe, expect, it } from 'vitest';
import { jackConfig, manifestHash } from '@graphmind-ai/jack-schema';
import {
  compile,
  compileProject,
  generateConfig,
  loadSource,
  parseConfigText,
  parseDocumentText,
  MAX_DOCUMENT_BYTES,
} from '../src/index.js';

const fixture = (name: string) => fileURLToPath(new URL(`./fixtures/${name}`, import.meta.url));
const dir = mkdtempSync(join(tmpdir(), 'jack-openapi-'));
afterAll(() => rmSync(dir, { recursive: true, force: true }));

describe('generateConfig (jack init)', () => {
  it('lists every operation explicitly, with comments, and round-trips to the same manifest', async () => {
    const { document } = await loadSource(fixture('petstore-3.0.yaml'));
    const { yaml, result, upstream } = generateConfig(document, {
      source: './petstore-3.0.yaml',
      upstream: 'https://petstore3.swagger.io/api/v3',
      today: '2026-11-09',
    });
    expect(upstream).toBe('https://petstore3.swagger.io/api/v3');
    expect(yaml).toContain('generated by `jack init` on 2026-11-09 from an OpenAPI 3.0 document');
    expect(yaml).toContain('# DELETE /api/v3/pet/{petId} — Deletes a pet.  [DESTRUCTIVE]');
    expect(yaml).toContain('# GET /api/v3/pet/findByTags — Finds Pets by tags.  [deprecated]');
    expect(yaml).toMatch(/ {2}delete_pet:\n {4}enabled: false/);
    expect(yaml).toMatch(/ {2}get_pet_by_id:\n {4}enabled: true/);
    // Suggested toolsets from tags.
    expect(yaml).toMatch(/toolsets:\n {2}pet:\n {4}tools: \[update_pet, add_pet, find_pets_by_status/);

    const config = parseConfigText(yaml, 'jack.yaml');
    expect(Object.keys(config.tools)).toHaveLength(result.tools.length);
    const again = compile(document, config);
    // Same tools, plus the toolsets the file suggested.
    expect(again.manifest.tools).toEqual(result.manifest.tools);
    expect(again.manifest.toolsets.map((t) => t.name)).toEqual(['pet', 'store', 'user']);
  });

  it('quotes hostile titles safely and keeps comments on one line', () => {
    const document = {
      openapi: '3.0.3',
      info: { title: 'Evil": true\nupstream: https://evil.test #', version: '1' },
      servers: [{ url: 'https://good.test' }],
      paths: {
        '/x': { get: { operationId: 'getX', summary: 'Line one\nupstream: https://evil.test', responses: {} } },
      },
    };
    const { yaml } = generateConfig(document, { source: './x.json' });
    const config = parseConfigText(yaml, 'jack.yaml');
    expect(config.upstream).toBe('https://good.test');
    expect(config.name).toBe('Evil": true\nupstream: https://evil.test #');
    expect(yaml).toContain('# GET /x — Line one upstream: https://evil.test');
  });

  it('a relative server with no URL to resolve against needs --upstream', async () => {
    const { document } = await loadSource(fixture('petstore-3.0.yaml'));
    expect(() => generateConfig(document, { source: './p.yaml' })).toThrow(/--upstream/);
  });
});

describe('loaders', () => {
  it('compileProject resolves `source` relative to jack.yaml and is deterministic', async () => {
    writeFileSync(join(dir, 'jack.yaml'), `source: ${JSON.stringify(fixture('petstore-2.0.json'))}\n`);
    const a = await compileProject(join(dir, 'jack.yaml'));
    const b = await compileProject(join(dir, 'jack.yaml'));
    expect(a.manifest.tools.map((t) => t.name)).toEqual(['get_pet_by_id']);
    expect(manifestHash(a.manifest)).toBe(manifestHash(b.manifest));
  });

  it('invalid jack.yaml is reported with the field that is wrong', () => {
    expect(() => parseConfigText('source: x\ntools:\n  a:\n    enabled: maybe\n', 'jack.yaml')).toThrow(/enabled/);
    expect(() => parseConfigText('tools: {}\n', 'jack.yaml')).toThrow(/source/);
    expect(() => parseConfigText('source: x\nupstream: not-a-url\n', 'jack.yaml')).toThrow(/upstream/);
  });

  it('YAML alias bombs are refused', () => {
    const bomb = ['a: &a [x, x, x, x, x, x, x, x, x, x]', 'b: &b [*a, *a, *a, *a, *a, *a, *a, *a, *a, *a]'];
    for (let i = 0; i < 12; i++) bomb.push(`c${i}: &c${i} [${Array(10).fill(i === 0 ? '*b' : `*c${i - 1}`).join(', ')}]`);
    expect(() => parseDocumentText(bomb.join('\n'), 'bomb.yaml')).toThrow(/not valid JSON or YAML/);
  });

  it('fetches URLs (resolving relative servers against the final URL) with a size cap', async () => {
    const text = await (await import('node:fs/promises')).readFile(fixture('petstore-3.0.yaml'), 'utf8');
    const fakeFetch = (async (url: string) => {
      const res = new Response(text, { status: 200 });
      Object.defineProperty(res, 'url', { value: url });
      return res;
    }) as unknown as typeof fetch;
    const src = await loadSource('https://petstore3.swagger.io/api/v3/openapi.yaml', { fetchImpl: fakeFetch });
    expect(src.documentUrl).toBe('https://petstore3.swagger.io/api/v3/openapi.yaml');
    const r = compile(src.document, jackConfig.parse({ source: 'x' }), { documentUrl: src.documentUrl! });
    expect(r.baseUrl).toBe('https://petstore3.swagger.io/api/v3');

    const huge = (async () =>
      new Response('x', { headers: { 'content-length': String(MAX_DOCUMENT_BYTES + 1) } })) as unknown as typeof fetch;
    await expect(loadSource('https://x.test/openapi.json', { fetchImpl: huge })).rejects.toThrow(/larger than/);
    const notFound = (async () => new Response('', { status: 404 })) as unknown as typeof fetch;
    await expect(loadSource('https://x.test/openapi.json', { fetchImpl: notFound })).rejects.toThrow(/HTTP 404/);
  });

  it('only files and http(s) URLs are sources', async () => {
    await expect(loadSource('file:///etc/passwd')).rejects.toThrow(/only http\(s\) URLs and files/);
    await expect(loadSource('ftp://x.test/a.json')).rejects.toThrow(/only http\(s\) URLs and files/);
    await expect(loadSource(join(dir, 'missing.json'))).rejects.toThrow(/cannot read/);
  });
});

describe('extends', () => {
  it('a variant file inherits everything and overrides auth and single tools', async () => {
    mkdirSync(join(dir, 'base'), { recursive: true });
    writeFileSync(
      join(dir, 'base', 'jack.yaml'),
      `source: ${JSON.stringify(fixture('petstore-2.0.json'))}\nauth: { mode: apikey }\ntools:\n  add_pet: { enabled: true, description: "Add a pet with a reviewed description." }\n  get_pet_by_id: { enabled: true }\n`,
    );
    writeFileSync(
      join(dir, 'jack.oidc.yaml'),
      'extends: ./base/jack.yaml\nauth: { mode: oidc, issuer: "https://login.test", clientId: jack, clientSecretRef: "env:X" }\ntools:\n  add_pet: { confirm: true }\n',
    );
    const r = await compileProject(join(dir, 'jack.oidc.yaml'));
    expect(r.config.auth).toMatchObject({ mode: 'oidc', issuer: 'https://login.test' });
    const add = r.manifest.tools.find((t) => t.name === 'add_pet')!;
    expect(add).toMatchObject({ confirm: true, description: 'Add a pet with a reviewed description.' });
    expect(r.manifest.tools.map((t) => t.name).sort()).toEqual(['add_pet', 'get_pet_by_id']);
  });

  it('loops are reported', async () => {
    writeFileSync(join(dir, 'a.yaml'), 'extends: ./b.yaml\nsource: x\n');
    writeFileSync(join(dir, 'b.yaml'), 'extends: ./a.yaml\n');
    await expect(compileProject(join(dir, 'a.yaml'))).rejects.toThrow(/loops back/);
  });
});

describe('environment substitution', () => {
  it('${VAR} and ${VAR:-default} in values; $${ is literal; a value cannot inject structure', async () => {
    writeFileSync(
      join(dir, 'env.yaml'),
      [
        `source: ${JSON.stringify(fixture('petstore-2.0.json'))}`,
        'upstream: "${PET_API:-https://petstore.swagger.io/v2}"',
        'name: "Pets $${literal}"',
        '',
      ].join('\n'),
    );
    const a = await compileProject(join(dir, 'env.yaml'), { env: {} });
    expect(a.baseUrl).toBe('https://petstore.swagger.io/v2');
    expect(a.manifest.name).toBe('Pets ${literal}');
    const b = await compileProject(join(dir, 'env.yaml'), { env: { PET_API: 'http://127.0.0.1:22123/v2' } });
    expect(b.baseUrl).toBe('http://127.0.0.1:22123/v2');
    // YAML-looking content stays one string value, so it fails URL validation instead of adding keys.
    await expect(compileProject(join(dir, 'env.yaml'), { env: { PET_API: 'https://x.test\nauth: { mode: none }' } })).rejects.toThrow();
  });

  it('a missing variable without a default is an error that names it', async () => {
    writeFileSync(join(dir, 'missing.yaml'), 'source: x\nupstream: "${NOPE_NOT_SET}"\n');
    await expect(compileProject(join(dir, 'missing.yaml'), { env: {} })).rejects.toThrow(/\$\{NOPE_NOT_SET\} is not set/);
  });
});
