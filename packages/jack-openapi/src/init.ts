/**
 * `jack init` — write a first jack.yaml for a document.
 *
 * The file lists EVERY operation with an explicit `enabled:` so the review
 * in a pull request is complete: reads start enabled, writes start disabled,
 * deprecated operations start disabled. Each entry carries a comment with
 * its method, path and summary so the reviewer doesn't need the spec open.
 * Toolsets are suggested from the document's tags.
 */
import { jackConfig } from '@graphmind-ai/jack-schema';
import { compile, type CompileResult } from './compile.js';

export interface InitOptions {
  /** Value written to `source:` (path relative to jack.yaml, or URL). */
  source: string;
  documentUrl?: string;
  /** Overrides the document's server. */
  upstream?: string;
  /** Date stamp for the header; injectable for tests. */
  today?: string;
}

export interface InitResult {
  yaml: string;
  result: CompileResult;
  upstream: string;
}

/** A YAML double-quoted scalar: JSON string syntax is valid YAML. */
const q = (s: string) => JSON.stringify(s);

/** Comments must stay on one line and never contain anything YAML could read. */
const comment = (s: string) => s.replace(/[\r\n]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 120);

const DIALECT_LABEL = { 'swagger-2.0': 'a Swagger 2.0', 'openapi-3.0': 'an OpenAPI 3.0', 'openapi-3.1': 'an OpenAPI 3.1' } as const;

const toolsetName = (tag: string) =>
  tag
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/^[^a-z]+/, '')
    .slice(0, 64);

export function generateConfig(document: unknown, opts: InitOptions): InitResult {
  // Compile with an empty config: this applies the default enablement rules
  // and gives us the generated names, exactly as `jack check` will see them.
  const base = jackConfig.parse({ source: opts.source, ...(opts.upstream ? { upstream: opts.upstream } : {}) });
  const result = compile(document, base, opts.documentUrl ? { documentUrl: opts.documentUrl } : {});
  const upstream = opts.upstream ?? result.baseUrl;

  const reads = result.tools.filter((t) => t.enabled).length;
  const lines: string[] = [
    `# jack.yaml — generated by \`jack init\`${opts.today ? ` on ${opts.today}` : ''} from ${DIALECT_LABEL[result.dialect]} document.`,
    '#',
    '# Review this file like code: it decides what AI clients may do with your API.',
    `# ${result.tools.length} operations found; ${reads} read operations start enabled.`,
    '# Operations that write start disabled: enable each one deliberately, and',
    '# give it a `description:` written for a model rather than for a human.',
    '#',
    '# Check with `jack check`; build the manifest with `jack build`.',
    '',
    `name: ${q(result.manifest.name)}`,
    `source: ${q(opts.source)}`,
    `upstream: ${q(upstream)}`,
    '',
    'auth:',
    '  mode: none   # oidc | link | apikey | none — sign-in arrives in M3 (oidc, apikey) and M5 (link)',
    '',
    'lint:',
    `  maxTools: ${base.lint.maxTools}`,
  ];

  const byTag = new Map<string, string[]>();
  for (const t of result.tools) {
    const tag = t.tags[0];
    if (tag === undefined) continue;
    const name = toolsetName(tag);
    if (!/^[a-z][a-z0-9-]{0,63}$/.test(name)) continue;
    byTag.set(name, [...(byTag.get(name) ?? []), t.key]);
  }
  if (byTag.size > 1) {
    lines.push('', '# Suggested from the document\'s tags. Disabled tools are left out of a toolset automatically.', 'toolsets:');
    for (const [name, tools] of byTag) {
      lines.push(`  ${name}:`, `    tools: [${tools.join(', ')}]`);
    }
  }

  lines.push('', 'tools:');
  for (const t of result.tools) {
    const flags = [t.kind === 'destructive' ? 'DESTRUCTIVE' : t.kind === 'write' ? 'writes' : '', t.deprecated ? 'deprecated' : '']
      .filter(Boolean)
      .join(', ');
    lines.push(
      `  # ${t.method} ${t.path}${t.summary ? ` — ${comment(t.summary)}` : ''}${flags ? `  [${flags}]` : ''}`,
      `  ${t.key}:`,
      `    enabled: ${t.enabled}`,
    );
  }

  return { yaml: `${lines.join('\n')}\n`, result, upstream };
}
