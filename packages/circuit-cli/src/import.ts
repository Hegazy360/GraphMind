/**
 * `circuit import n8n|pipedream <export.json>` — turn an exported workflow
 * into a Circuit workflow skeleton (M7).
 *
 * Best effort, and honest about it: every node/step becomes a `ctx.step`
 * in execution order; what can't be ported mechanically becomes a step that
 * THROWS a `TODO(circuit-import)` error carrying the original node's
 * parameters in a comment. Running the skeleton therefore pauses at the
 * first unported step — fix-and-resume is the porting workflow.
 *
 * Why these two: Pipedream Workflows shuts down 2027-03-31 and n8n is the
 * tool teams outgrow; both leave users with JSON exports and no runtime.
 */
import type { JsonValue } from '@graphmind-ai/circuit-schema';

export interface GeneratedWorkflow {
  /** kebab-case workflow name. */
  name: string;
  fileName: string;
  source: string;
  /** Steps generated in total / of which need manual porting. */
  steps: number;
  todos: string[];
  notes: string[];
}

const kebab = (raw: string): string =>
  raw
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')
    .toLowerCase()
    .replace(/^-|-$/g, '') || 'imported';

const js = (v: unknown): string => JSON.stringify(v ?? null);
/** Multi-line JSON inside a block comment, with comment-enders defused. */
const commentJson = (v: unknown): string =>
  JSON.stringify(v ?? {}, null, 2).replaceAll('*/', '*\\/');

function uniqueNamer(): (base: string) => string {
  const seen = new Map<string, number>();
  return (base) => {
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return n === 0 ? base : `${base}-${n + 1}`;
  };
}

function header(kind: string, workflowName: string, notes: string[]): string {
  return [
    '/**',
    ` * '${workflowName}' — generated by \`circuit import ${kind}\` on ${new Date().toISOString().slice(0, 10)}.`,
    ' *',
    ' * Best-effort skeleton: steps run in the original order; steps that could',
    ' * not be ported mechanically THROW a TODO error, so a run pauses at the',
    ' * first one — port it, then retry the step from the dashboard.',
    ...notes.map((n) => ` * NOTE: ${n}`),
    ' */',
    "import { workflow, z } from '@graphmind-ai/circuit-sdk';",
    '',
  ].join('\n');
}

const todoStep = (stepName: string, what: string, params: unknown): string =>
  [
    `  await ctx.step(${js(stepName)}, () => {`,
    `    /* TODO(circuit-import): port ${what}. Original parameters:`,
    ...commentJson(params).split('\n').map((l) => `    ${l}`),
    '    */',
    `    throw new Error('TODO(circuit-import): port ${what.replaceAll("'", '"')}');`,
    '  });',
  ].join('\n');

// ---------------------------------------------------------------- n8n ----

interface N8nNode {
  name: string;
  type: string;
  parameters?: Record<string, JsonValue>;
  disabled?: boolean;
}
interface N8nExport {
  name?: string;
  nodes?: N8nNode[];
  connections?: Record<string, { main?: Array<Array<{ node: string }>> }>;
}

const N8N_TRIGGERS = /trigger|webhook|cron|schedule|emailreadimap|start/i;

/** Walk the main-connection graph breadth-first from the trigger nodes. */
function n8nOrder(nodes: N8nNode[], connections: N8nExport['connections'] = {}): N8nNode[] {
  const byName = new Map(nodes.map((n) => [n.name, n]));
  const starts = nodes.filter((n) => N8N_TRIGGERS.test(n.type));
  const queue = (starts.length > 0 ? starts : nodes.slice(0, 1)).map((n) => n.name);
  const seen = new Set<string>();
  const ordered: N8nNode[] = [];
  while (queue.length > 0) {
    const name = queue.shift() as string;
    if (seen.has(name)) continue;
    seen.add(name);
    const node = byName.get(name);
    if (node) ordered.push(node);
    for (const branch of connections?.[name]?.main ?? []) {
      for (const edge of branch ?? []) queue.push(edge.node);
    }
  }
  // Unreachable nodes still matter to the reader: append them.
  for (const n of nodes) if (!seen.has(n.name)) ordered.push(n);
  return ordered;
}

export function importN8n(raw: unknown, sourceLabel = 'n8n export'): GeneratedWorkflow {
  const data = raw as N8nExport;
  if (!Array.isArray(data?.nodes) || data.nodes.length === 0) {
    throw new Error(`${sourceLabel}: not an n8n workflow export (expected a "nodes" array)`);
  }
  const name = kebab(data.name ?? 'imported-n8n-workflow');
  const nextName = uniqueNamer();
  const notes: string[] = [
    "n8n expressions like ={{ $json.field }} are not ported — pass values between steps via the returned variables instead.",
  ];
  const todos: string[] = [];
  const body: string[] = [];
  const triggers: string[] = [];
  let steps = 0;

  for (const node of n8nOrder(data.nodes, data.connections)) {
    if (node.disabled === true) {
      body.push(`  // (skipped: n8n node '${node.name}' was disabled)`);
      continue;
    }
    const type = node.type;
    const stepName = nextName(kebab(node.name));
    const p = node.parameters ?? {};

    if (N8N_TRIGGERS.test(type)) {
      if (/cron|schedule/i.test(type)) {
        triggers.push(`{ type: 'cron', schedule: '0 9 * * *' /* TODO(circuit-import): original rule: ${js(p)} */ }`);
      } else if (/webhook/i.test(type)) {
        triggers.push(`{ type: 'api' }`);
      } else {
        triggers.push(`{ type: 'api' } /* was ${type} */`);
      }
      continue;
    }

    steps += 1;
    if (type === 'n8n-nodes-base.wait' && typeof p.amount === 'number') {
      const unit = String(p.unit ?? 'seconds').charAt(0); // seconds|minutes|hours|days → s m h d
      body.push(`  await ctx.sleep(${js(stepName)}, '${p.amount}${unit}');`);
    } else if (type === 'n8n-nodes-base.httpRequest' && typeof p.url === 'string') {
      const method = String(p.method ?? 'GET').toUpperCase();
      body.push(
        [
          `  const ${camel(stepName)} = await ctx.step(${js(stepName)}, async () => {`,
          `    // TODO(circuit-import): verify this port of n8n 'HTTP Request' (auth, headers, body not ported)`,
          `    const res = await fetch(${js(p.url)}, { method: ${js(method)} });`,
          '    if (!res.ok) throw new Error(`HTTP ${res.status}`);',
          `    return await res.json();`,
          '  });',
        ].join('\n'),
      );
      todos.push(stepName);
    } else if (/n8n-nodes-base\.(if|switch|merge)$/.test(type)) {
      body.push(
        `  // BRANCH: n8n '${node.name}' (${type}) — Circuit workflows branch with plain JavaScript if/else.`,
      );
      body.push(todoStep(stepName, `n8n branching node '${node.name}' (${type})`, p));
      todos.push(stepName);
    } else {
      body.push(todoStep(stepName, `n8n node '${node.name}' (${type})`, p));
      todos.push(stepName);
    }
  }
  if (triggers.length === 0) triggers.push(`{ type: 'api' }`);

  const source = [
    header('n8n', name, notes),
    `export const ${camel(name)} = workflow(`,
    `  {`,
    `    name: ${js(name)},`,
    `    triggers: [${triggers.join(', ')}],`,
    `  },`,
    `  async (ctx, input) => {`,
    body.join('\n') || '  // (no nodes)',
    `    return { done: true };`,
    `  },`,
    `);`,
    '',
  ].join('\n');
  return { name, fileName: `${name}.circuit.mjs`, source, steps, todos, notes };
}

// ----------------------------------------------------------- pipedream ----

interface PipedreamStep {
  namespace?: string;
  name?: string;
  code?: string;
  component?: { key?: string };
  action?: string;
  props?: Record<string, JsonValue>;
}
interface PipedreamExport {
  name?: string;
  triggers?: Array<{ type?: string; cron?: { cron?: string } }>;
  steps?: PipedreamStep[];
}

export function importPipedream(raw: unknown, sourceLabel = 'pipedream export'): GeneratedWorkflow {
  const data = raw as PipedreamExport;
  if (!Array.isArray(data?.steps) || data.steps.length === 0) {
    throw new Error(`${sourceLabel}: not a Pipedream workflow export (expected a "steps" array)`);
  }
  const name = kebab(data.name ?? 'imported-pipedream-workflow');
  const nextName = uniqueNamer();
  const notes = [
    'Pipedream `steps.<name>.$return_value` references become plain variables here.',
    'Connected-account auths are not ported: use ctx.mcp(...) connections or environment variables.',
  ];
  const todos: string[] = [];
  const body: string[] = [];
  let steps = 0;

  const triggers = (data.triggers ?? []).map((t) =>
    t?.cron?.cron ? `{ type: 'cron', schedule: ${js(t.cron.cron)} }` : `{ type: 'api' }`,
  );
  if (triggers.length === 0) triggers.push(`{ type: 'api' }`);

  for (const step of data.steps) {
    const label = step.namespace ?? step.name ?? `step-${steps + 1}`;
    const stepName = nextName(kebab(label));
    steps += 1;
    if (typeof step.code === 'string' && step.code.trim() !== '') {
      body.push(
        [
          `  await ctx.step(${js(stepName)}, async () => {`,
          `    /* TODO(circuit-import): original Pipedream code step — port it below.`,
          ...step.code.replaceAll('*/', '*\\/').split('\n').map((l) => `    ${l}`),
          '    */',
          `    throw new Error('TODO(circuit-import): port Pipedream code step ${js(label).slice(1, -1)}');`,
          '  });',
        ].join('\n'),
      );
    } else {
      const what = step.component?.key ?? step.action ?? 'action step';
      body.push(todoStep(stepName, `Pipedream ${what} ('${label}')`, step.props ?? step));
    }
    todos.push(stepName);
  }

  const source = [
    header('pipedream', name, notes),
    `export const ${camel(name)} = workflow(`,
    `  {`,
    `    name: ${js(name)},`,
    `    triggers: [${triggers.join(', ')}],`,
    `  },`,
    `  async (ctx, input) => {`,
    body.join('\n'),
    `    return { done: true };`,
    `  },`,
    `);`,
    '',
  ].join('\n');
  return { name, fileName: `${name}.circuit.mjs`, source, steps, todos, notes };
}

function camel(kebabName: string): string {
  const s = kebabName.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  return /^[a-z_$]/i.test(s) ? s : `wf${s}`;
}
