/**
 * Python + the OpenAI or Anthropic SDK: `graphmind.init`, `instrument_*` on
 * the client, the tool stubs through `gm.wrap_tools`, and a tool-call loop
 * capped at MAX_STEPS inside `with gm.run(...)`.
 *
 * `.env` is loaded by a six-line function rather than a dependency, and the
 * generated project needs only `graphmind-ai` plus the provider SDK.
 */
import { VERSION } from '../../version.js';
import { PROVIDER_ENV_KEY, type WorkflowSpec } from '../spec.js';
import { paramSummary, paramsJsonSchema, pyLiteral, pySignature, pyString, stubResult } from './shared.js';
import { envExample } from './ts-common.js';
import type { GeneratedFile } from './types.js';
import type { LocalPackages } from '../local-packages.js';

export const PY_DEPS = {
  'graphmind-ai': `>=${VERSION}`,
  openai: '>=1.40',
  anthropic: '>=0.34',
} as const;

function toolsFile(spec: WorkflowSpec): string {
  const lines: string[] = [
    `"""The tools ${spec.name} can call.`,
    '',
    'Generated by the GraphMind builder as stubs: each returns a fixed value so the',
    'agent runs end to end. Replace the body of each with the real implementation;',
    'keep the signature and TOOL_SCHEMAS in step (the schema is what the model',
    'reads).',
    '',
    'main.py wraps TOOLS with gm.wrap_tools(), which is what lets the debugger hold',
    'a call before it runs, edit its arguments, or inject a result.',
    '"""',
    '',
    'from __future__ import annotations',
    '',
    'from typing import Any',
    '',
  ];
  for (const tool of spec.tools) {
    lines.push('');
    lines.push(`def ${tool.name}(${pySignature(tool.params)}) -> Any:`);
    lines.push(`    """${tool.description.replace(/"""/g, '\\"\\"\\"')}"""`);
    lines.push(`    # TODO: implement. Receives ${paramSummary(tool.params)}.`);
    lines.push(`    return ${pyLiteral(stubResult(tool), 1)}`);
    lines.push('');
  }
  lines.push('');
  lines.push('TOOLS: dict[str, Any] = {');
  for (const tool of spec.tools) lines.push(`    ${pyString(tool.name)}: ${tool.name},`);
  lines.push('}');
  lines.push('');
  const schemas = spec.tools.map((tool) =>
    spec.provider === 'anthropic'
      ? { name: tool.name, description: tool.description, input_schema: paramsJsonSchema(tool.params) }
      : {
          type: 'function',
          function: { name: tool.name, description: tool.description, parameters: paramsJsonSchema(tool.params) },
        },
  );
  lines.push(`TOOL_SCHEMAS: list[dict[str, Any]] = ${pyLiteral(schemas)}`);
  lines.push('');
  return lines.join('\n');
}

const ENV_LOADER = `def load_env(path: Path = Path(".env")) -> None:
    """Read KEY=VALUE lines from .env into the environment. Nothing is printed."""
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))`;

function header(spec: WorkflowSpec, framework: string): string {
  return `"""${spec.name} - generated by the GraphMind workflow builder (graphmind-ai ${VERSION}).

Run \`npx graphmind-ai\` in another terminal, then \`python main.py\` (inside the
virtualenv). The run shows up in the viewer live; an error pauses it before
your code sees it.

Instrumentation: graphmind.init, gm.instrument_${framework} (the client is
instrumented in place), gm.wrap_tools (gated tool functions) and gm.run (the
run boundary). Remove them and this is a plain ${framework} SDK script.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any

import graphmind
`;
}

function envCheck(spec: WorkflowSpec): string {
  const key = PROVIDER_ENV_KEY[spec.provider];
  return `load_env()
if not os.environ.get(${pyString(key)}):
    print(${pyString(`${key} is not set. Add it to .env (see .env.example).`)}, file=sys.stderr)
    sys.exit(1)`;
}

function constants(spec: WorkflowSpec): string {
  const hasSystem = spec.systemPrompt !== undefined && spec.systemPrompt.trim() !== '';
  return `MODEL = ${pyString(spec.model)}
MAX_STEPS = ${spec.maxSteps}
${hasSystem ? `SYSTEM = ${pyString(spec.systemPrompt ?? '')}\n` : ''}PROMPT = ${pyString(spec.prompt)}`;
}

function openaiMain(spec: WorkflowSpec): string {
  const hasTools = spec.tools.length > 0;
  const hasSystem = spec.systemPrompt !== undefined && spec.systemPrompt.trim() !== '';
  return `${header(spec, 'openai')}from openai import OpenAI

from tools import TOOLS${hasTools ? ', TOOL_SCHEMAS' : ''}


${ENV_LOADER}


${envCheck(spec)}

${constants(spec)}

gm = graphmind.init(app=${pyString(spec.name)})
# Wait for the debugger so pause-on-error is armed before the first step.
# Fails open: no debugger within the timeout just means an undebugged run.
attached = gm.ready()
print("attached to GraphMind" if attached else "no GraphMind server found; running undebugged", file=sys.stderr)

client = gm.instrument_openai(OpenAI())
# Gated: the debugger can hold a call before it runs, edit its arguments, or
# inject a result. The index is by the name the model chose.
tools = gm.wrap_tools(TOOLS)


def main() -> None:
    with gm.run(${pyString(spec.name)}):
        messages: list[Any] = [
${hasSystem ? '            {"role": "system", "content": SYSTEM},\n' : ''}            {"role": "user", "content": PROMPT},
        ]
        for _ in range(MAX_STEPS):
            completion = client.chat.completions.create(
                model=MODEL,
                messages=messages,
${hasTools ? '                tools=TOOL_SCHEMAS,\n' : ''}            )
            message = completion.choices[0].message
            calls = [c for c in (message.tool_calls or []) if c.type == "function"]
            if not calls:
                print(message.content or "")
                return
            messages.append(message)
            for call in calls:
                fn = tools.get(call.function.name)
                try:
                    args = json.loads(call.function.arguments or "{}")
                except json.JSONDecodeError:
                    args = {}
                output = fn(**args) if fn is not None else {"error": f"unknown tool {call.function.name}"}
                messages.append({"role": "tool", "tool_call_id": call.id, "content": json.dumps(output)})
        print(f"stopped after {MAX_STEPS} steps", file=sys.stderr)


if __name__ == "__main__":
    try:
        main()
    except graphmind.GraphMindAbortError:
        print("(run aborted from the debugger)", file=sys.stderr)
    finally:
        gm.dispose()
`;
}

function anthropicMain(spec: WorkflowSpec): string {
  const hasTools = spec.tools.length > 0;
  const hasSystem = spec.systemPrompt !== undefined && spec.systemPrompt.trim() !== '';
  return `${header(spec, 'anthropic')}from anthropic import Anthropic

from tools import TOOLS${hasTools ? ', TOOL_SCHEMAS' : ''}


${ENV_LOADER}


${envCheck(spec)}

${constants(spec)}

gm = graphmind.init(app=${pyString(spec.name)})
# Wait for the debugger so pause-on-error is armed before the first step.
# Fails open: no debugger within the timeout just means an undebugged run.
attached = gm.ready()
print("attached to GraphMind" if attached else "no GraphMind server found; running undebugged", file=sys.stderr)

# An unscoped Anthropic key needs the workspace named per request (the
# ANTHROPIC_WORKSPACE_ID line in .env); a scoped key sends no header.
workspace_id = os.environ.get("ANTHROPIC_WORKSPACE_ID")
client = gm.instrument_anthropic(
    Anthropic(default_headers={"anthropic-workspace-id": workspace_id} if workspace_id else None)
)
# Gated: the debugger can hold a call before it runs, edit its arguments, or
# inject a result. The index is by the name the model chose.
tools = gm.wrap_tools(TOOLS)


def main() -> None:
    with gm.run(${pyString(spec.name)}):
        messages: list[Any] = [{"role": "user", "content": PROMPT}]
        for _ in range(MAX_STEPS):
            message = client.messages.create(
                model=MODEL,
                max_tokens=1024,
${hasSystem ? '                system=SYSTEM,\n' : ''}${hasTools ? '                tools=TOOL_SCHEMAS,\n' : ''}                messages=messages,
            )
            messages.append({"role": "assistant", "content": message.content})
            if message.stop_reason != "tool_use":
                print("".join(block.text for block in message.content if block.type == "text"))
                return
            results = []
            for block in message.content:
                if block.type != "tool_use":
                    continue
                fn = tools.get(block.name)
                output = fn(**block.input) if fn is not None else {"error": f"unknown tool {block.name}"}
                results.append({"type": "tool_result", "tool_use_id": block.id, "content": json.dumps(output)})
            messages.append({"role": "user", "content": results})
        print(f"stopped after {MAX_STEPS} steps", file=sys.stderr)


if __name__ == "__main__":
    try:
        main()
    except graphmind.GraphMindAbortError:
        print("(run aborted from the debugger)", file=sys.stderr)
    finally:
        gm.dispose()
`;
}

export function generatePython(spec: WorkflowSpec, local?: LocalPackages): GeneratedFile[] {
  const providerDep = spec.provider === 'anthropic' ? `anthropic${PY_DEPS.anthropic}` : `openai${PY_DEPS.openai}`;
  // A checkout's version is unpublished: install the SDK from the checkout itself.
  const graphmindDep = local === undefined ? `graphmind-ai${PY_DEPS['graphmind-ai']}` : local.pythonRequirement;
  return [
    { path: 'requirements.txt', content: `${graphmindDep}\n${providerDep}\n` },
    { path: 'main.py', content: spec.provider === 'anthropic' ? anthropicMain(spec) : openaiMain(spec) },
    { path: 'tools.py', content: toolsFile(spec) },
    { path: '.env.example', content: envExample(spec) },
  ];
}
