/**
 * Load `.env` with Node's built-in loader (22.13 has it): no dependency, and
 * the file is read into the environment only, never printed.
 */
export function tsEnvLoader(provider: WorkflowSpec['provider']): string {
  const key = PROVIDER_ENV_KEY[provider];
  return `// Credentials live in .env (owner-only, git-ignored), never in code: ${key}.
// The builder wrote it; edit it by hand or from the Build page. Node loads it
// here without printing anything. Missing file = the SDK reads the environment.
try {
  process.loadEnvFile('.env');
} catch {
  // no .env yet
}
if (process.env[${tsString(key)}] === undefined || process.env[${tsString(key)}] === '') {
  console.error(${tsString(`${key} is not set. Add it to .env (see .env.example).`)});
  process.exit(1);
}`;
}

/** The tool stubs as plain async functions (Anthropic and OpenAI SDK targets). */
export function tsPlainToolsFile(spec: WorkflowSpec): string {
  const lines: string[] = [
    '/**',
    ` * The tools ${spec.name} can call. Generated by the GraphMind builder as stubs:`,
    ' * each returns a fixed value so the agent runs end to end. Replace the body of',
    ' * each with the real implementation; keep the signature and the schema in',
    ' * step (the schema is what the model reads).',
    ' *',
    ' * main.ts wraps this record with gm.wrapTools(), which is what lets the',
    ' * debugger hold a call before it runs, edit its arguments, or inject a result.',
    ' */',
    '',
  ];
  if (spec.tools.length === 0) {
    lines.push('export const tools = {} as const;', '');
    return lines.join('\n');
  }
  lines.push('export const tools = {');
  for (const tool of spec.tools) {
    const input = tsInputType(tool.params);
    lines.push(`  /** ${tool.description.replace(/\*\//g, '* /')} */`);
    lines.push(`  ${tool.name}: async (input: ${input}) => {`);
    lines.push(`    // TODO: implement. Receives ${paramSummary(tool.params)}.`);
    if (tool.params.length > 0) lines.push('    void input;');
    lines.push(`    return ${tsLiteral(stubResult(tool), 2)};`);
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

export function envExample(spec: WorkflowSpec): string {
  const key = PROVIDER_ENV_KEY[spec.provider];
  return `# Copy to .env and fill in. .env is git-ignored and must stay that way.
${key}=

# Where the GraphMind debugger listens (the default is fine for a local server).
# GRAPHMIND_URL=ws://127.0.0.1:4747/ingest
`;
}

export interface ReadmeCommands {
  install: string[];
  start: string;
  /** An alternative install line (the uv route for Python). */
  alternative?: { title: string; lines: string[] } | undefined;
  /** Where the GraphMind adapter came from. */
  source: 'registry' | 'checkout';
}

export function readme(spec: WorkflowSpec, commands: ReadmeCommands): string {
  const target = TARGETS[spec.target];
  const key = PROVIDER_ENV_KEY[spec.provider];
  const toolList =
    spec.tools.length === 0
      ? '_No tools yet._'
      : spec.tools.map((t) => `- \`${t.name}\` — ${t.description}`).join('\n');
  return `# ${spec.name}

${wrap(spec.description ?? `An agent built with ${target.framework} (${target.language}), instrumented with GraphMind.`).join('\n')}

Generated by the GraphMind workflow builder (graphmind-ai ${VERSION}). It is
plain code: edit anything, and keep editing it in your editor from here on.

## Run it

1. Put your key in \`.env\` (git-ignored; the builder may already have written it):

   \`\`\`
   ${key}=...
   \`\`\`

2. Start the debugger in another terminal and leave it open:

   \`\`\`sh
   npx graphmind-ai
   \`\`\`

3. Install and run${target.language === 'python' ? ' (Python 3.10 or newer)' : ' (Node 22.13 or newer)'}:

   \`\`\`sh
${commands.install.map((c) => `   ${c}`).join('\n')}
   ${commands.start}
   \`\`\`
${
  commands.alternative === undefined
    ? ''
    : `
   ${commands.alternative.title}

   \`\`\`sh
${commands.alternative.lines.map((c) => `   ${c}`).join('\n')}
   \`\`\`
`
}${
  commands.source === 'checkout'
    ? `
   The GraphMind adapter in this project comes from the local checkout that
   generated it (a \`file:\` tarball / path), because that checkout's version is
   not published yet. Regenerate from a published \`graphmind-ai\` to get the
   registry pin instead.
`
    : ''
}
The run appears in the viewer as it happens. An error pauses it before your
code sees it; from the viewer you can inspect the call, inject a result, edit
its arguments, retry, or abort. With no debugger running the instrumentation
is a no-op and the agent runs normally.

## Tools

${toolList}

Each tool is a stub that returns a fixed value. Replace the stub bodies in
\`${target.language === 'typescript' ? 'src/tools.ts' : 'tools.py'}\` with real code; the schemas next to them are what the model reads.

## Model

- Provider: ${spec.provider}
- Model: \`${spec.model}\`
- Max steps: ${spec.maxSteps}

Docs: ${target.docs}
`;
}
