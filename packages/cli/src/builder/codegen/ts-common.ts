/**
 * The parts every TypeScript target shares: the manifest, tsconfig, the
 * `.env` loader, the tool stubs' shape, and the README.
 *
 * Generated projects pin the published adapters at this CLI's own version
 * (`^VERSION`), so a project created by graphmind-ai 0.6.x gets 0.6.x
 * adapters, which speak the same wire protocol as the server that made it.
 */
import { VERSION } from '../../version.js';
import { PROVIDER_ENV_KEY, TARGETS, type WorkflowSpec } from '../spec.js';
import { paramSummary, stubResult, tsInputType, tsLiteral, tsString, wrap } from './shared.js';
import type { LocalPackages } from '../local-packages.js';

/** Dependency floors for the provider SDKs the generated code imports. */
export const TS_DEPS = {
  ai: '^7.0.79',
  '@ai-sdk/anthropic': '^4.0.42',
  '@ai-sdk/openai': '^4.0.47',
  '@anthropic-ai/sdk': '^0.121.0',
  openai: '^6.0.0',
  zod: '^4.0.0',
  tsx: '^4.19.0',
  typescript: '^5.9.0',
  '@types/node': '^22.0.0',
} as const;

/**
 * The manifest. With `local` (this CLI runs from a checkout) every
 * `@graphmind-ai/*` dependency becomes a `file:` tarball and `overrides` send
 * the adapter's own `@graphmind-ai/client` / `schema` to tarballs too.
 */
export function tsPackageJson(spec: WorkflowSpec, dependencies: Record<string, string>, local?: LocalPackages): string {
  const resolved: Record<string, string> = { ...dependencies };
  let overrides: Record<string, string> | undefined;
  if (local !== undefined) {
    for (const name of Object.keys(resolved)) {
      const tarball = local.npm[name];
      if (tarball !== undefined) resolved[name] = `file:${tarball}`;
    }
    overrides = {};
    for (const name of ['@graphmind-ai/client', '@graphmind-ai/schema']) {
      const tarball = local.npm[name];
      if (tarball !== undefined) overrides[name] = `file:${tarball}`;
    }
  }
  const sorted = Object.fromEntries(Object.entries(resolved).sort(([a], [b]) => a.localeCompare(b)));
  return `${JSON.stringify(
    {
      name: spec.name,
      private: true,
      description: spec.description ?? `${spec.name} — an agent instrumented with GraphMind`,
      type: 'module',
      engines: { node: '>=22.13' },
      scripts: {
        start: 'tsx src/main.ts',
        typecheck: 'tsc --noEmit',
      },
      dependencies: sorted,
      devDependencies: {
        '@types/node': TS_DEPS['@types/node'],
        tsx: TS_DEPS.tsx,
        typescript: TS_DEPS.typescript,
      },
      ...(overrides === undefined ? {} : { overrides }),
    },
    null,
    2,
  )}\n`;
}

