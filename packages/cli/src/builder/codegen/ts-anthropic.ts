/**
 * TypeScript + the Anthropic SDK: `gm.wrapClient` around the client, the
 * tool stubs through `gm.wrapTools`, and the tool-use loop the adapter
 * README shows — generated once into `src/loop.ts` so the root agent and
 * every sub-agent run the same code.
 *
 * MCP nodes arrive as `src/mcp.ts`: their tools join the schema list and the
 * wrapped caller record, so the model and the debugger treat them exactly
 * like local tools.
 */
import { VERSION } from '../../version.js';
import type { WorkflowSpec } from '../spec.js';
import { rootWiring } from '../spec.js';
import { paramsJsonSchema, tsLiteral, tsString } from './shared.js';
import { MCP_SDK_DEP, hasMcp, mcpFile, mcpPrefix } from './mcp-ts.js';
import { anthropicLoopFile, sdkAgentsFile } from './ts-loop.js';
import { TS_CONFIG, TS_DEPS, envExample, tsEnvLoader, tsPackageJson, tsPlainToolsFile } from './ts-common.js';
import type { GeneratedFile } from './types.js';
import type { LocalPackages } from '../local-packages.js';

function schemasFile(spec: WorkflowSpec): string {
  const schemas = spec.tools.map((tool) => ({
    name: tool.name,
    description: tool.description,
    input_schema: paramsJsonSchema(tool.params),
  }));
  return `/**
 * The tool definitions the model reads. Keep them in step with src/tools.ts.
 */
import type Anthropic from '@anthropic-ai/sdk';

export const toolSchemas: Anthropic.Tool[] = ${tsLiteral(schemas)};
`;
}

function mainFile(spec: WorkflowSpec): string {
  const hasTools = spec.tools.length > 0;
  const hasSystem = spec.systemPrompt !== undefined && spec.systemPrompt.trim() !== '';
  const mcp = hasMcp(spec);
  const subs = spec.subAgents.length > 0;
  const root = rootWiring(spec);
  const rootNames = [...root.tools.map((t) => t.name), ...root.subAgents.map((a) => a.name)];
  const rootPrefixes = root.mcpServers.map(mcpPrefix);

  const imports = [
    "import Anthropic from '@anthropic-ai/sdk';",
    "import { graphmind, isAbortError } from '@graphmind-ai/anthropic';",
    "import { runLoop, selectSchemas, selectTools, type ToolFns } from './loop.js';",
    "import { tools as workflowTools } from './tools.js';",
    ...(hasTools ? ["import { toolSchemas } from './schemas.js';"] : []),
    ...(mcp ? ["import { callersOf, connectMcp } from './mcp.js';"] : []),
    ...(subs ? ["import { subAgentSchemas, subAgentTools } from './agents.js';"] : []),
  ].join('\n');

  const mcpBlock = mcp
    ? `
// Every MCP server on the canvas, connected and listed once. Their tools keep
// the server's own JSON Schema; nothing is re-described here.
const mcp = await connectMcp(APP);
const mcpSchemas: Anthropic.Tool[] = Object.values(mcp.tools).map((entry) => ({
  name: entry.name,
  description: entry.description,
  input_schema: entry.inputSchema as Anthropic.Tool['input_schema'],
}));
`
    : '';
  const wrapInput = mcp ? '{ ...workflowTools, ...callersOf(mcp.tools) }' : 'workflowTools';
  const baseSchemas = [...(hasTools ? ['...toolSchemas'] : []), ...(mcp ? ['...mcpSchemas'] : [])];
  const subBlock = subs
    ? `const agents = subAgentTools({ client, schemas, tools: wrapped });
const tools: ToolFns = { ...wrapped, ...agents };
const allSchemas: Anthropic.Tool[] = [...schemas, ...subAgentSchemas];
`
    : `const tools = wrapped;
const allSchemas = schemas;
`;
  const closing = mcp ? '  await mcp.close();\n  await gm.dispose();' : '  await gm.dispose();';

  return `/**
 * ${spec.name} — generated by the GraphMind workflow builder (graphmind-ai ${VERSION}).
 *
 * Run \`npx graphmind-ai\` in another terminal, then \`npm start\`. The run shows
 * up in the viewer live; an error pauses it before your code sees it.
 *
 * Instrumentation: gm.wrapClient (a Proxy over the SDK client), gm.wrapTools
 * (gated tool functions) and gm.run (the run boundary). Remove them and this
 * is a plain Anthropic SDK script.
 */
${imports}

${tsEnvLoader(spec.provider)}

const APP = ${tsString(spec.name)};
const MODEL = ${tsString(spec.model)};
const MAX_STEPS = ${spec.maxSteps};
${hasSystem ? `const SYSTEM = ${tsString(spec.systemPrompt ?? '')};\n` : ''}const PROMPT = ${tsString(spec.prompt)};
// What the ROOT agent is wired to on the canvas: tools and sub-agents by
// name, MCP servers by the prefix their tools carry.
const ROOT_TOOLS: string[] = ${tsLiteral(rootNames)};
const ROOT_MCP: string[] = ${tsLiteral(rootPrefixes)};

const gm = graphmind({ app: APP });
const attached = await gm.ready();
console.error(attached ? 'attached to GraphMind' : 'no GraphMind server found; running undebugged');

// A key that is not scoped to a workspace must name one per request (the
// ANTHROPIC_WORKSPACE_ID line in .env); a scoped key needs no header.
const workspaceId = process.env.ANTHROPIC_WORKSPACE_ID;
const client = gm.wrapClient(
  new Anthropic(workspaceId ? { defaultHeaders: { 'anthropic-workspace-id': workspaceId } } : {}),
);
${mcpBlock}
// Gated: the debugger can hold a call before it runs, edit its arguments, or
// inject a result. The index is by the name the model chose.
const wrapped = gm.wrapTools(${wrapInput}) as ToolFns;
const schemas: Anthropic.Tool[] = [${baseSchemas.join(', ')}];
${subBlock}
try {
  await gm.run(APP, async () => {
    await runLoop({
      client,
      model: MODEL,
${hasSystem ? '      system: SYSTEM,\n' : ''}      prompt: PROMPT,
      schemas: selectSchemas(allSchemas, ROOT_TOOLS, ROOT_MCP),
      tools: selectTools(tools, ROOT_TOOLS, ROOT_MCP),
      maxSteps: MAX_STEPS,
      onText: (text) => console.log(text),
    });
  });
} catch (error) {
  if (isAbortError(error)) console.error('(run aborted from the debugger)');
  else throw error;
} finally {
${closing}
}
`;
}

export function generateTsAnthropic(spec: WorkflowSpec, local?: LocalPackages): GeneratedFile[] {
  const mcp = hasMcp(spec);
  const dependencies: Record<string, string> = {
    '@anthropic-ai/sdk': TS_DEPS['@anthropic-ai/sdk'],
    '@graphmind-ai/anthropic': `^${VERSION}`,
    ...(mcp ? { '@modelcontextprotocol/sdk': MCP_SDK_DEP } : {}),
  };
  const files: GeneratedFile[] = [
    { path: 'package.json', content: tsPackageJson(spec, dependencies, local) },
    { path: 'tsconfig.json', content: TS_CONFIG },
    { path: 'src/main.ts', content: mainFile(spec) },
    { path: 'src/loop.ts', content: anthropicLoopFile() },
    { path: 'src/tools.ts', content: tsPlainToolsFile(spec) },
  ];
  if (spec.tools.length > 0) files.push({ path: 'src/schemas.ts', content: schemasFile(spec) });
  if (mcp) files.push({ path: 'src/mcp.ts', content: mcpFile(spec) });
  if (spec.subAgents.length > 0) files.push({ path: 'src/agents.ts', content: sdkAgentsFile(spec, 'anthropic') });
  files.push({ path: '.env.example', content: envExample(spec) });
  return files;
}
