/**
 * `src/mcp.ts`: the MCP client side of a generated project, shared by all
 * three TypeScript targets.
 *
 * One connection per MCP node on the canvas. Each server's tools are listed
 * at startup and exposed to the model as `server_tool`, so two servers that
 * both publish `search` stay apart, and a sub-agent can be given "everything
 * from this server" by prefix without knowing the tool names in advance.
 *
 * Credentials: an HTTP server that needs one names an environment variable
 * (`headerEnv`), read here and sent as `Authorization: Bearer ...`. The token
 * is never printed — a missing variable is reported by NAME only.
 *
 * The callers this returns are plain async functions, so main.ts can hand
 * them to `gm.wrapTools` with the local stubs: an MCP call then holds,
 * steps, and injects in the debugger exactly like a local tool.
 */
import type { McpServerSpec, WorkflowSpec } from '../spec.js';
import { tsLiteral } from './shared.js';
import { usedMcpServers } from '../spec.js';

/** Floor for the MCP SDK the generated client imports. */
export const MCP_SDK_DEP = '^1.26.0';

/** The prefix every tool from `server` gets: `fs_read_file`. */
export function mcpPrefix(server: McpServerSpec): string {
  return `${server.name}_`;
}

export function hasMcp(spec: WorkflowSpec): boolean {
  return usedMcpServers(spec).length > 0;
}

interface WireServer {
  name: string;
  transport: 'stdio' | 'http';
  command: string;
  args: string[];
  url: string;
  headerEnv: string | null;
  allow: string[];
}

function wire(servers: readonly McpServerSpec[]): WireServer[] {
  return servers.map((server) => ({
    name: server.name,
    transport: server.transport,
    command: server.command,
    args: [...server.args],
    url: server.url,
    headerEnv: server.headerEnv ?? null,
    allow: [...server.tools],
  }));
}

export function mcpFile(spec: WorkflowSpec): string {
  const servers = wire(usedMcpServers(spec));
  return `/**
 * The MCP servers ${spec.name} connects to, and the tools they publish.
 *
 * Generated by the GraphMind workflow builder. Each server is listed once at
 * startup; its tools arrive as \`server_tool\` so names from two servers never
 * collide. Edit SERVERS to point at a different server, or replace this file
 * entirely — it is plain code that uses the public MCP SDK.
 *
 * Nothing here holds a secret: a server that needs a bearer token names the
 * environment variable it lives in, and the value is read from .env at
 * startup and never printed.
 */
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

export interface McpTool {
  /** \`server_tool\`: unique across servers, and a legal tool name for every provider. */
  name: string;
  description: string;
  /** The server's own JSON Schema for the tool's arguments. */
  inputSchema: Record<string, unknown>;
  call: (input: unknown) => Promise<unknown>;
}

export interface McpServerConfig {
  name: string;
  transport: 'stdio' | 'http';
  command: string;
  args: string[];
  url: string;
  /** The variable holding the bearer token, or null when the server needs none. */
  headerEnv: string | null;
  /** Only these tool names are exposed. Empty = everything the server lists. */
  allow: string[];
}

export const SERVERS: McpServerConfig[] = ${tsLiteral(servers)};

/** The prefix a server's tools get. Sub-agents select whole servers with it. */
export function prefixOf(server: McpServerConfig): string {
  return \`\${server.name}_\`;
}

/**
 * The Authorization header for an HTTP server, if it asked for one. A token
 * that is not set is a warning naming the VARIABLE, never the value.
 */
function httpOptions(server: McpServerConfig): { requestInit: { headers: Record<string, string> } } | undefined {
  if (server.headerEnv === null) return undefined;
  const token = process.env[server.headerEnv];
  if (token === undefined || token === '') {
    console.error(\`\${server.headerEnv} is not set; connecting to \${server.name} with no Authorization header\`);
    return undefined;
  }
  return { requestInit: { headers: { Authorization: \`Bearer \${token}\` } } };
}

function transportFor(server: McpServerConfig) {
  if (server.transport === 'stdio') {
    // argv as given, no shell: the command is one program, the arguments are
    // separate strings, and nothing is re-parsed.
    return new StdioClientTransport({ command: server.command, args: server.args, stderr: 'inherit' });
  }
  const options = httpOptions(server);
  return new StreamableHTTPClientTransport(new URL(server.url), options);
}

export interface McpConnection {
  /** Every exposed tool, by its \`server_tool\` name. */
  tools: Record<string, McpTool>;
  close: () => Promise<void>;
}

/**
 * Connect every server and list its tools. A server that refuses to connect
 * is reported and skipped: one unreachable MCP server must not take the
 * whole agent down before it has said anything.
 */
export async function connectMcp(appName: string): Promise<McpConnection> {
  const clients: Client[] = [];
  const tools: Record<string, McpTool> = {};
  for (const server of SERVERS) {
    const client = new Client({ name: appName, version: '1.0.0' });
    try {
      await client.connect(transportFor(server));
    } catch (error) {
      console.error(\`MCP server \${server.name} did not connect: \${error instanceof Error ? error.message : String(error)}\`);
      continue;
    }
    clients.push(client);
    const listed = await client.listTools();
    for (const published of listed.tools) {
      if (server.allow.length > 0 && !server.allow.includes(published.name)) continue;
      const name = \`\${prefixOf(server)}\${published.name}\`.replace(/[^A-Za-z0-9_]/g, '_').slice(0, 64);
      tools[name] = {
        name,
        description: published.description ?? \`\${published.name} on the \${server.name} MCP server\`,
        inputSchema: (published.inputSchema as Record<string, unknown> | undefined) ?? {
          type: 'object',
          properties: {},
        },
        call: async (input: unknown) => {
          const result = await client.callTool({
            name: published.name,
            arguments: (input ?? {}) as Record<string, unknown>,
          });
          // Prefer the typed result; fall back to the content blocks.
          return result.structuredContent ?? result.content ?? result;
        },
      };
    }
    console.error(\`MCP: \${server.name} connected (\${listed.tools.length} tools)\`);
  }
  return {
    tools,
    close: async () => {
      for (const client of clients) {
        try {
          await client.close();
        } catch {
          // already gone; nothing to do on the way out
        }
      }
    },
  };
}

/** The plain callers, for gm.wrapTools alongside the local stubs. */
export function callersOf(tools: Record<string, McpTool>): Record<string, (input: unknown) => Promise<unknown>> {
  return Object.fromEntries(Object.values(tools).map((tool) => [tool.name, tool.call]));
}
`;
}

/** The `.env` names the MCP nodes need, for the Build page's key fields. */
export function mcpEnvNames(spec: WorkflowSpec): { name: string; server: string }[] {
  const out: { name: string; server: string }[] = [];
  for (const server of usedMcpServers(spec)) {
    if (server.headerEnv !== undefined && server.headerEnv !== '') {
      out.push({ name: server.headerEnv, server: server.name });
    }
  }
  return out;
}

/** `['fs_', 'github_']` — the prefixes one agent's MCP servers contribute. */
export function prefixLiteral(servers: readonly McpServerSpec[]): string {
  return tsLiteral(servers.map(mcpPrefix));
}
