/**
 * TypeScript + the OpenAI SDK: `gm.wrapClient` around the client, the tool
 * stubs through `gm.wrapTools`, and a Chat Completions tool-call loop capped
 * at MAX_STEPS. Each tool call is passed as the wrapped tool's second
 * argument so the debugger correlates the execution with the model's call.
 */
import { VERSION } from '../../version.js';
import type { WorkflowSpec } from '../spec.js';
import { paramsJsonSchema, tsLiteral, tsString } from './shared.js';
import { TS_CONFIG, TS_DEPS, envExample, tsEnvLoader, tsPackageJson, tsPlainToolsFile } from './ts-common.js';
import type { GeneratedFile } from './types.js';
import type { LocalPackages } from '../local-packages.js';

function schemasFile(spec: WorkflowSpec): string {
  const schemas = spec.tools.map((tool) => ({
    type: 'function',
    function: {
      name: tool.name,
      description: tool.description,
      parameters: paramsJsonSchema(tool.params),
    },
  }));
  return `/**
 * The tool definitions the model reads. Keep them in step with src/tools.ts.
 */
import type OpenAI from 'openai';

export const toolSchemas: OpenAI.Chat.Completions.ChatCompletionTool[] = ${tsLiteral(schemas)};
`;
}

function mainFile(spec: WorkflowSpec): string {
  const hasTools = spec.tools.length > 0;
  const hasSystem = spec.systemPrompt !== undefined && spec.systemPrompt.trim() !== '';
  return `/**
 * ${spec.name} — generated by the GraphMind workflow builder (graphmind-ai ${VERSION}).
 *
 * Run \`npx graphmind-ai\` in another terminal, then \`npm start\`. The run shows
 * up in the viewer live; an error pauses it before your code sees it.
 *
 * Instrumentation: gm.wrapClient (a Proxy over the SDK client), gm.wrapTools
 * (gated tool functions) and gm.run (the run boundary). Remove them and this
 * is a plain OpenAI SDK script.
 */
import OpenAI from 'openai';
import { graphmind, isAbortError } from '@graphmind-ai/openai';
import { tools as workflowTools } from './tools.js';
${hasTools ? "import { toolSchemas } from './schemas.js';\n" : ''}
${tsEnvLoader(spec.provider)}

const MODEL = ${tsString(spec.model)};
const MAX_STEPS = ${spec.maxSteps};
${hasSystem ? `const SYSTEM = ${tsString(spec.systemPrompt ?? '')};\n` : ''}const PROMPT = ${tsString(spec.prompt)};

const gm = graphmind({ app: ${tsString(spec.name)} });
const attached = await gm.ready();
console.error(attached ? 'attached to GraphMind' : 'no GraphMind server found; running undebugged');

const client = gm.wrapClient(new OpenAI());
// Gated: the debugger can hold a call before it runs, edit its arguments, or
// inject a result. The index is by the name the model chose.
const tools = gm.wrapTools(workflowTools) as Record<string, (input: unknown, call?: unknown) => Promise<unknown>>;

try {
  await gm.run(${tsString(spec.name)}, async () => {
    const messages: OpenAI.Chat.Completions.ChatCompletionMessageParam[] = [
${hasSystem ? "      { role: 'system', content: SYSTEM },\n" : ''}      { role: 'user', content: PROMPT },
    ];
    for (let step = 0; step < MAX_STEPS; step += 1) {
      const completion = await client.chat.completions.create({
        model: MODEL,
        messages,
${hasTools ? '        tools: toolSchemas,\n' : ''}      });
      const message = completion.choices[0]?.message;
      if (message === undefined) throw new Error('the model returned no choices');
      const calls = (message.tool_calls ?? []).filter((call) => call.type === 'function');
      if (calls.length === 0) {
        console.log(message.content ?? '');
        return;
      }
      messages.push(message);
      // Parallel calls gate independently: hold one, let the others run.
      const results = await Promise.all(
        calls.map(async (call) => {
          const fn = tools[call.function.name];
          let args: unknown = {};
          try {
            args = JSON.parse(call.function.arguments || '{}');
          } catch {
            // the model produced unparseable arguments; the tool sees {}
          }
          const output = fn === undefined ? { error: \`unknown tool \${call.function.name}\` } : await fn(args, call);
          return { role: 'tool' as const, tool_call_id: call.id, content: JSON.stringify(output) };
        }),
      );
      messages.push(...results);
    }
    console.error(\`stopped after \${MAX_STEPS} steps\`);
  });
} catch (error) {
  if (isAbortError(error)) console.error('(run aborted from the debugger)');
  else throw error;
} finally {
  await gm.dispose();
}
`;
}

export function generateTsOpenai(spec: WorkflowSpec, local?: LocalPackages): GeneratedFile[] {
  const dependencies: Record<string, string> = {
    '@graphmind-ai/openai': `^${VERSION}`,
    openai: TS_DEPS.openai,
  };
  const files: GeneratedFile[] = [
    { path: 'package.json', content: tsPackageJson(spec, dependencies, local) },
    { path: 'tsconfig.json', content: TS_CONFIG },
    { path: 'src/main.ts', content: mainFile(spec) },
    { path: 'src/tools.ts', content: tsPlainToolsFile(spec) },
    { path: '.env.example', content: envExample(spec) },
  ];
  if (spec.tools.length > 0) files.splice(4, 0, { path: 'src/schemas.ts', content: schemasFile(spec) });
  return files;
}
